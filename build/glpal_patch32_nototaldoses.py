#!/usr/bin/env python3
"""
Patch 32 - hide the Total Doses card.

Why
    Total Doses counts every dose record; Logged Doses counts only records
    marked isManual (Log Dose, Edit Dose, CSV import). The difference is dose
    records generated by dosing plans, which Marc does not use and which are
    hidden since patch 27. Marc asked to remove the card he is not using:
    Total Doses, whose only extra content is plan-generated doses.

Fix
    - render guard (`!1&&`, the patch-15 technique) on the Total Doses card
    - the Doses card grid goes from `grid-cols-2 lg:grid-cols-4` to
      `grid-cols-3`, so the remaining three cards (Current Level, Logged
      Doses, Avg Peak (14d)) sit in one row at every width; `grid-cols-3`
      exists in the shipped CSS

What this deliberately does NOT change
    - Logged Doses, Current Level, Avg Peak (14d)
    - Wye's totalDoses value (still computed, not rendered)
    - stored data

Usage
    python glpal_patch32_nototaldoses.py IN.js OUT.js
"""

from pathlib import Path
import hashlib
import sys

EXPECTED_INPUT_SHA256 = "d24fc503a1d812934b081709608d56d30bbbb5e89d9ddf017910afeed2857c43"
EXPECTED_OUTPUT_SHA256 = "1632b24bc59b99b6024c8ce648402540dc36c7160e06786db0814b2c8bbe3b37"

OLD = ('grid grid-cols-2 lg:grid-cols-4 gap-2 sm:gap-3 overflow-visible",children:[S.jsxs("div",{className:Pe,'
       'children:[S.jsx("p",{className:Qe.label,children:"Total Doses"})')
NEW = ('grid grid-cols-3 gap-2 sm:gap-3 overflow-visible",children:[!1&&S.jsxs("div",{className:Pe,'
       'children:[S.jsx("p",{className:Qe.label,children:"Total Doses"})')


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def main():
    if len(sys.argv) != 3:
        raise SystemExit("Usage: python glpal_patch32_nototaldoses.py INPUT_JS OUTPUT_JS")
    src, out_path = Path(sys.argv[1]), Path(sys.argv[2])
    raw = src.read_bytes()
    actual_in = sha256_bytes(raw)
    if actual_in != EXPECTED_INPUT_SHA256:
        raise RuntimeError("Input is not the verified patch-31 bundle.\n"
                           f"Expected: {EXPECTED_INPUT_SHA256}\n  Actual: {actual_in}")
    text = raw.decode("utf-8")
    if text.count(OLD) != 1:
        raise RuntimeError(f"Doses grid / Total Doses anchor found {text.count(OLD)} times, expected 1")
    guards = text.count("!1&&")
    text = text.replace(OLD, NEW, 1)
    if text.count("!1&&") != guards + 1 or text.count('"Total Doses"') != 1:
        raise RuntimeError("guard did not apply exactly once")

    data = text.encode("utf-8")
    actual_out = sha256_bytes(data)
    if EXPECTED_OUTPUT_SHA256 and actual_out != EXPECTED_OUTPUT_SHA256:
        raise RuntimeError(f"output sha mismatch\nExpected: {EXPECTED_OUTPUT_SHA256}\n  Actual: {actual_out}")
    out_path.write_bytes(data)
    print(f"Wrote {out_path}")
    print("Total Doses card hidden; Doses grid is 3 across")
    print(f"SHA-256: {actual_out}")


if __name__ == "__main__":
    main()

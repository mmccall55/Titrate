def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def die(msg: str):
    raise SystemExit("FAIL: " + msg)


def sub_once(text: str, pattern: str, repl: str, label: str, flags=0) -> str:
    new, n = re.subn(pattern, repl, text, flags=flags)
    if n != 1:
        die(f"{label}: expected 1 substitution, made {n}")
    return new


# ---------------------------------------------------------------- stage 1
def extract():
    if not ZIP.exists():
        die(f"{ZIP.name} not found. Move it here from your Downloads folder.")
    actual = sha256(ZIP)
    if actual != EXPECTED_ZIP_SHA:
        die("ZIP SHA-256 mismatch.\n"
            f"  expected {EXPECTED_ZIP_SHA}\n  actual   {actual}")
    if UPSTREAM.exists():
        shutil.rmtree(UPSTREAM)
    with zipfile.ZipFile(ZIP) as z:
        for name in z.namelist():
            if name.startswith("/") or ".." in name:
                die(f"unsafe zip entry: {name}")
        z.extractall(UPSTREAM)
    print(f"[1] extracted {ZIP.name}  sha256 ok")



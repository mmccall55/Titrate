# ---------------------------------------------------------------- stage 3
def build_fork(patched: Path):
    if FORK.exists():
        shutil.rmtree(FORK)
    # _original-css2.txt is a capture-only artefact and is deliberately not copied
    shutil.copytree(UPSTREAM, FORK,
                    ignore=shutil.ignore_patterns("_original-css2.txt"))

    # patched bundle replaces upstream under the filename index.html expects
    shutil.copy2(patched, FORK / BUNDLE_REL)
    if sha256(FORK / BUNDLE_REL) != SHIP_SHA:
        die("fork bundle is not the expected shipping build")

    # lazily-imported Capacitor shim, captured separately
    if not WEB_SHIM.exists():
        die(f"{WEB_SHIM.name} missing; the app 404s without it")
    if sha256(WEB_SHIM) != EXPECTED_WEB_SHA:
        die(f"{WEB_SHIM.name} sha mismatch: {sha256(WEB_SHIM)}")
    shutil.copy2(WEB_SHIM, FORK / "assets" / WEB_SHIM.name)

    # ---- recolour: purple -> muted orange ----------------------------
    if not PALETTE.exists():
        die("palette.json missing. Run make_palette.py first.")
    r = subprocess.run([sys.executable, str(ROOT / "recolour.py"),
                        str(FORK / BUNDLE_REL), str(FORK / CSS_REL)],
                       capture_output=True, text=True)
    if r.returncode != 0:
        die("recolour.py failed:\n" + r.stdout + r.stderr)
    print("[3a] recoloured\n" + "\n".join("     " + l for l in r.stdout.strip().splitlines()))

    # ---- brand icons -------------------------------------------------
    icons = ["favicon.ico", "logo192.png", "logo512.png"]
    missing = [i for i in icons if not (BRAND_DIR / i).exists()]
    if missing:
        die(f"brand assets missing: {missing}. Run make_icons.py first.")
    for i in icons:
        shutil.copy2(BRAND_DIR / i, FORK / i)

    # ---- index.html -------------------------------------------------
    html = (FORK / "index.html").read_text(encoding="utf-8")

    html = sub_once(html, r"<title>[^<]*</title>", f"<title>{BRAND_LONG}</title>", "title")
    html = sub_once(html, r'(<meta name="theme-color" content=")[^"]*(")',
                    r"\g<1>" + ACCENT + r"\g<2>", "theme colour")
    # keep the deployed site out of search indexes
    html = sub_once(html, r'(<meta name="viewport"[^>]*>)',
                    r'\1\n    <meta name="robots" content="noindex, nofollow, noarchive, nosnippet" />',
                    "noindex meta")
    html = sub_once(html, r'(<meta name="apple-mobile-web-app-title" content=")[^"]*(")',
                    r"\g<1>" + BRAND + r"\g<2>", "apple web app title")
    html = sub_once(html, r'(<meta\s*\n?\s*name="description"\s*\n?\s*content=")[^"]*(")',
                    r"\g<1>" + BRAND_DESC + r"\g<2>", "meta description")

    # remove Google Fonts preconnects + stylesheet (now self-hosted)
    html, n = re.subn(r'\s*<link rel="preconnect" href="https://fonts\.[^>]*>', "", html)
    if n != 2:
        die(f"expected 2 font preconnects, removed {n}")
    html = sub_once(html, r'\s*<link href="https://fonts\.googleapis\.com/css2[^>]*>', "",
                    "remove Google Fonts stylesheet")

    # root-relative -> relative so the package works under any base path
    for attr, val in [("href", "/favicon.ico"), ("href", "/logo192.png"),
                      ("href", "/manifest.json"), ("src", "/" + BUNDLE_REL),
                      ("href", "/" + CSS_REL)]:
        html = sub_once(html, re.escape(f'{attr}="{val}"'), f'{attr}="./{val.lstrip("/")}"',
                        f"relativise {val}")

    # self-hosted fonts + service worker registration
    html = sub_once(html, r'(\s*)<link rel="manifest"',
                    r'\1<link rel="stylesheet" href="./fonts.css" />\1<link rel="manifest"',
                    "insert fonts.css link")
    html = sub_once(html, r"\s*</body>", """
    <script>
      if ('serviceWorker' in navigator) {
        window.addEventListener('load', function () {
          navigator.serviceWorker.register('./sw.js', { scope: './' });
        });
      }
    </script>
  </body>""", "insert service worker registration")

    for bad in ("cloudflareinsights", "fonts.googleapis", "fonts.gstatic", 'href="/', 'src="/',
                "GLPal"):
        if bad in html:
            die(f"index.html still contains {bad!r}")
    (FORK / "index.html").write_text(html, encoding="utf-8")

    # ---- manifest.json ----------------------------------------------
    mf = json.loads((FORK / "manifest.json").read_text(encoding="utf-8"))
    mf["name"] = BRAND_LONG
    mf["short_name"] = BRAND
    mf["description"] = BRAND_DESC
    mf["theme_color"] = ACCENT
    mf["background_color"] = "#1A1815"
    mf["start_url"] = "./"
    mf["scope"] = "./"
    mf["id"] = "./"
    for icon in mf.get("icons", []):
        if not icon["src"].startswith("./"):
            icon["src"] = "./" + icon["src"].lstrip("/")
    (FORK / "manifest.json").write_text(json.dumps(mf, indent=2) + "\n", encoding="utf-8")

    # ---- service worker ---------------------------------------------
    precache = sorted(
        "./" + p.relative_to(FORK).as_posix()
        for p in FORK.rglob("*")
        if p.is_file() and p.name not in {"sw.js", ".nojekyll", "robots.txt"}
    )
    precache = ["./"] + precache
    fingerprint = hashlib.sha256(
        "".join(sorted(sha256(p) for p in FORK.rglob("*") if p.is_file())).encode()
    ).hexdigest()[:12]

    (FORK / "sw.js").write_text(SW_TEMPLATE.replace("__VERSION__", fingerprint)
                                .replace("__PRECACHE__", json.dumps(precache, indent=2)),
                                encoding="utf-8")

    (FORK / ".nojekyll").write_text("", encoding="utf-8")
    (FORK / "robots.txt").write_text("User-agent: *\nDisallow: /\n", encoding="utf-8")
    print(f"[3] fork assembled  {len(precache) - 1} precached files  cache v{fingerprint}")
    return precache, fingerprint


SW_TEMPLATE = """// Titrate - offline service worker
// Generated by build_fork.py. Cache-first for the app shell; the app itself
// stores all health data in IndexedDB and this worker never touches it.
const CACHE = 'titrate-__VERSION__';
const PRECACHE = __PRECACHE__;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((c) => c.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' }))))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(names.filter((n) => n !== CACHE).map((n) => caches.delete(n))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;   // never proxy third-party requests

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(() => caches.match('./index.html', { ignoreSearch: true })
        .then((r) => r || caches.match('./')))
    );
    return;
  }

  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res && res.ok && res.type === 'basic') {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      });
    })
  );
});
"""


# ---------------------------------------------------------------- stage 4
def verify(precache):
    problems = []
    html = (FORK / "index.html").read_text(encoding="utf-8")
    css = (FORK / CSS_REL).read_text(encoding="utf-8", errors="replace")
    fonts = (FORK / "fonts.css").read_text(encoding="utf-8")

    for label, text in (("index.html", html), ("app css", css), ("fonts.css", fonts)):
        for bad in ("fonts.googleapis.com", "fonts.gstatic.com", "cloudflareinsights"):
            if bad in text:
                problems.append(f"{label} references {bad}")

    for ref in re.findall(r'(?:href|src)="\./([^"]+)"', html):
        if not (FORK / ref).exists():
            problems.append(f"index.html references missing {ref}")
    for ref in re.findall(r"url\(\./([^)]+)\)", fonts):
        if not (FORK / ref).exists():
            problems.append(f"fonts.css references missing {ref}")
    for entry in precache[1:]:
        if not (FORK / entry[2:]).exists():
            problems.append(f"sw precache references missing {entry}")

    if not (FORK / "sw.js").exists():
        problems.append("sw.js missing")

    # branding: nothing user-visible may still say GLPal. The database name
    # inside the bundle is the single deliberate exception.
    if "GLPal" in (FORK / "manifest.json").read_text(encoding="utf-8"):
        problems.append("manifest.json still says GLPal")
    if "GLPal" in html:
        problems.append("index.html still says GLPal")
    bundle_hits = (FORK / BUNDLE_REL).read_text(encoding="utf-8", errors="replace").count("GLPal")
    if bundle_hits != 1:
        problems.append(f"bundle has {bundle_hits} GLPal strings, expected 1 (the DB name)")
    for icon in ("favicon.ico", "logo192.png", "logo512.png"):
        if (FORK / icon).read_bytes() != (BRAND_DIR / icon).read_bytes():
            problems.append(f"{icon} is not the rebranded asset")

    print("\n[4] verification")
    if problems:
        for p in problems:
            print("    FAIL " + p)
        raise SystemExit(1)
    print("    ok  no external requests, no missing references, all precache entries exist")


# ---------------------------------------------------------------- stage 5
def mirror():
    """Copy the verified tree into the project folder (writes only, no unlinks)."""
    built = {p.relative_to(FORK).as_posix() for p in FORK.rglob("*") if p.is_file()}
    for rel in sorted(built):
        dst = DEST / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(FORK / rel, dst)

    stale = sorted(
        {p.relative_to(DEST).as_posix() for p in DEST.rglob("*") if p.is_file()} - built
    ) if DEST.exists() else []
    print(f"[5] mirrored {len(built)} files into {DEST.name}/")
    if stale:
        print("    WARNING: leftover files from an earlier build (delete manually):")
        for s in stale:
            print("      " + s)


if __name__ == "__main__":
    print(f"work dir: {WORK}")
    extract()
    patched = patch()
    precache, _ = build_fork(patched)
    verify(precache)
    mirror()
    total = sum(p.stat().st_size for p in FORK.rglob("*") if p.is_file())
    print(f"\nfork/ ready  {total:,} bytes")

#!/usr/bin/env python3
"""
Assemble the GLPal editable-dose fork from the captured upstream ZIP.

Inputs (same directory):
  glpal-upstream.zip   captured 2026-08-13 from https://glpal.app/app/
  glpal_patch.py       deterministic six-part patcher

Outputs:
  upstream/            untouched extracted upstream assets
  glpal-index.js       untouched upstream bundle (convenience copy)
  glpal-index-editable.js  patched bundle
  fork/                complete, self-contained, base-path-agnostic PWA

Every stage is hash-verified. The script refuses to continue on any mismatch.
"""

